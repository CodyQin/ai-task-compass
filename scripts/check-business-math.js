'use strict';
const assert = require('node:assert/strict');
const {calculate} = require('./business-math.js');
const base={runs:200,oldMinutes:15,newMinutes:4,reviewMinutes:3,maintenanceHours:2,upfrontCash:3000,monthlyFees:100,maintenanceCash:50,cashSavings:500,incrementalMargin:0,avoidedLoss:0,qualityOK:true,benefitsConfirmed:true};
const r=calculate(base);
assert.ok(Math.abs(r.releasedHours-24.666666666666668)<1e-9);
assert.equal(r.monthlyNetCash,350);
assert.ok(Math.abs(r.paybackMonths-3000/350)<1e-9);
assert.ok(Math.abs(r.firstYearROI-0.4)<1e-9);
assert.equal(calculate({...base,qualityOK:false}).firstYearROI,null);
assert.equal(calculate({...base,benefitsConfirmed:false}).paybackMonths,null);
assert.equal(calculate({...base,upfrontCash:0}).firstYearROI,null);
assert.equal(calculate({...base,upfrontCash:0}).paybackMonths,null);
assert.equal(calculate({...base,cashSavings:150}).paybackMonths,null);
assert.equal(calculate({...base,cashSavings:0}).paybackMonths,null);
assert.ok(calculate({...base,cashSavings:0}).firstYearROI<0);
assert.ok(calculate({...base,newMinutes:30}).releasedHours<0);
assert.throws(()=>calculate({...base,runs:0.5}));
assert.throws(()=>calculate({...base,monthlyFees:-1}));
assert.throws(()=>calculate({...base,oldMinutes:NaN}));
assert.throws(()=>calculate({...base,cashSavings:Infinity}));
assert.throws(()=>calculate({...base,runs:1e308,oldMinutes:1e308}));
assert.throws(()=>calculate({...base,cashSavings:1e308}));
console.log('Business estimates: capacity, cash, acceptance gates, zero/negative return and invalid-input checks passed.');
